function inRing(p, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [x, y] = ring[i], [u, v] = ring[j];
    if ((y > p[1]) !== (v > p[1]) && p[0] < (u - x) * (p[1] - y) / (v - y) + x) inside = !inside;
  }
  return inside;
}
